# ============================================================================


def is_valid_key(key):
    """
    Проверяет, правильный ли ключ ввёл пользователь.

    Как работает:
        Перебирает номера от 1 до 100 000 и для каждого
        генерирует ключ. Если какой-то совпал с введённым —
        значит, ключ правильный.

    Почему перебор:
        Мы НЕ храним список всех ключей. Каждый ключ
        проверяется «на лету» по формуле. Это безопаснее.

    Что принимает:
        key (str) — ключ, который ввёл пользователь.

    Что возвращает:
        True  — если ключ правильный
        False — если неправильный.
    """
    # Если ключ пустой — сразу False
    if not key:
        return False

    # Приводим ключ к верхнему регистру и убираем пробелы по краям
    key = key.strip().upper()

    # Ключ должен начинаться с "SP-"
    if not key.startswith("SP-"):
        return False

    # Перебираем все возможные номера от 1 до 100 000
    for n in range(1, 100000):
        # Генерируем ключ для этого номера
        if _generate_key_from_number(n) == key:
            # Совпало — ключ правильный
            return True

    # Ничего не совпало — ключ неправильный
    return False


def load_license():
    """
    Загружает данные лицензии из файла.

    Проверяет оба пути (APPDATA и LOCALAPPDATA).
    Если в каком-то из них есть файл с валидным ключом —
    возвращает статус «активирована».

    Что возвращает:
        dict — {"activated": True/False, "key": "SP-..." или None}.
    """
    # Идём по всем возможным путям
    for path in _get_paths():
        # Если файл существует
        if os.path.exists(path):
            try:
                # Открываем файл на чтение
                with open(path, "r", encoding="utf-8") as f:
                    data = json.load(f)

                # Проверяем: есть ли флаг активации и ключ
                if data.get("activated") and data.get("key"):
                    # Проверяем, что ключ всё ещё валидный
                    if is_valid_key(data["key"]):
                        return {"activated": True, "key": data["key"]}

            except (json.JSONDecodeError, IOError):
                # Если файл битый или не читается — пропускаем
                continue

    # Ничего не нашли — программа не активирована
    return {"activated": False, "key": None}


def save_license(key):
    """
    Сохраняет ключ активации в оба места (APPDATA и LOCALAPPDATA).

    Что принимает:
        key (str) — ключ активации.

    Что возвращает:
        True  — если удалось сохранить хотя бы куда-то
        False — если никуда не удалось.
    """
    # Данные, которые будем записывать
    data = {"activated": True, "key": key.strip().upper()}

    # Флаг: сохранили ли куда-нибудь
    saved_anywhere = False

    # Пробуем сохранить в каждый путь
    for path in _get_paths():
        try:
            # Создаём папку, если её ещё нет
            # exist_ok=True — не ругаться, если папка уже есть
            os.makedirs(os.path.dirname(path), exist_ok=True)

            # Открываем файл на запись
            with open(path, "w", encoding="utf-8") as f:
                # Записываем JSON
                # ensure_ascii=False — чтобы русские буквы читались
                # indent=2 — красивое форматирование
                json.dump(data, f, ensure_ascii=False, indent=2)

            saved_anywhere = True

        except (IOError, OSError):
            # Не удалось сохранить в это место — пробуем следующее
            continue

    return saved_anywhere


def is_activated():
    """
    Быстрая проверка: активирована ли программа.

    Что возвращает:
        True  — если активирована
        False — если демо-версия.
    """
    return load_license().get("activated", False)
