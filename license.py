# license.py — управление лицензией SchoolPlanner
# ============================================================================
#
# Этот файл отвечает за защиту программы:
#   - проверяет, активирована ли программа;
#   - хранит ключ активации в системной папке;
#   - проверяет, правильный ли ключ ввёл пользователь.
#
# Как это работает:
#   1. При запуске программа спрашивает у этого файла: «Активирована?»
#   2. Если да — работает полная версия.
#   3. Если нет — работает демо-версия (до 5 классов).
#   4. Пользователь вводит ключ → файл проверяет его.
#   5. Если ключ верный — сохраняет его в папку.
#   6. При следующем запуске — ключ уже есть, программа сразу полная.
# ============================================================================


# Импортируем os — нужен, чтобы работать с папками и файлами и всем вокруг программы
# (узнать путь к системной папке, создать её, проверить существование файла, в отличии от sys,
# который работает с самой системой - запустить, завершить работу той или иной программы и тд)

import os

# Импортируем json — чтобы сохранять и читать данные в формате JSON
# (license.json — это файл, где хранится ключ)

import json

# Импортируем hashlib — нужен для хеширования (MD5)
# Хеширование — это когда из строки делают «отпечаток»
# (одну строку превращают в другую, но обратно уже не вернуть)
import hashlib

# ----------------------------------------------------------------------------
# Константы — то, что не меняется
# ----------------------------------------------------------------------------

# Имя программы — используется в пути к папке
APP_NAME = "SchoolPlanner"

# Имя файла, где хранится ключ
LICENSE_FILE = "license.json"

# Сколько классов можно в демо-версии
DEMO_MAX_CLASSES = 5

# Секретная строка/ключ (её ещё называют «соль»).
# Она подмешивается к номеру ключа перед хешированием.
# Благодаря ей никто не сможет угадать ключи по формуле.
# ⚠️ ВАЖНО: не публиковать, не менять, не терять!
SECRET_SALT = "SchoolPlanner_2026_SecretKey_v1"


# ============================================================================
# Вспомогательные функции
# ============================================================================


def _get_paths():
    """
    Возвращает список путей, где искать и хранить файл лицензии.

    Зачем два пути:
        - %APPDATA% — основная папка программы;
        - %LOCALAPPDATA% — резервная папка.
        Если пользователь случайно удалит одну — вторая восстановит ключ.

    Что возвращает:
        список строк (путей к файлу).
    """
    # Создаём пустой список, куда будем складывать пути
    paths = []

      # Первый путь: %APPDATA% (данные пользователя).
    # Пример: C:\Users\Алексей\AppData\Roaming
    # os.environ.get() — безопасно берёт значение переменной.
    # Если переменной нет — вернёт None (а не ошибку).
    appdata = os.environ.get("APPDATA")
    if appdata:
        # os.path.join() соединяет части пути с правильным разделителем
        # (\ на Windows, / на Linux).
        paths.append(os.path.join(appdata, APP_NAME, LICENSE_FILE))

    # Второй путь: %LOCALAPPDATA% (резерв — данные компьютера).
    # Пример: C:\Users\Алексей\AppData\Local
    localappdata = os.environ.get("LOCALAPPDATA")
    if localappdata:
        paths.append(os.path.join(localappdata, APP_NAME, LICENSE_FILE))

    # Возвращаем оба пути: основной + резервный
    return paths


def _generate_key_from_number(n):
    """
    Превращает число n в ключ формата SP-XXXX-XXXX-XXXX.

    Как это работает:
        1. Соединяем секретную строку и число через дефис: «СОЛЬ-1»
        2. Считаем MD5 от этой строки — получаем 32 hex-символа
        3. Берём первые 12 символов и разбиваем на 3 группы по 4
        4. Получаем ключ: SP-A3B7-C9D2-E5F1

    Что принимает:
        n (int) — номер ключа (1, 2, 3, ...)

    Что возвращает:
        str — ключ вида "SP-XXXX-XXXX-XXXX".
    """
    # Собираем строку: секретный ключ + дефис + число
    # Например: "SchoolPlanner_2026_SecretKey_v1-1"
    raw = f"{SECRET_SALT}-{n}"

    # Считаем MD5-хеш.
    # .encode() — превращаем строку в байты (MD5 работает с байтами).
    # .hexdigest() — получаем строку из 32 hex-символов.
    # .upper() — делаем все буквы заглавными.
    h = hashlib.md5(raw.encode()).hexdigest().upper()

    # Берём первые 12 символов и разбиваем на 3 группы по 4:
    # h[0:4]   — первые 4 символа
    # h[4:8]   — следующие 4
    # h[8:12]  — ещё 4
    part1 = h[0:4]
    part2 = h[4:8]
    part3 = h[8:12]

    # Собираем ключ: "SP-XXXX-XXXX-XXXX"
    return f"SP-{part1}-{part2}-{part3}"


