
# keygen.py — генератор ключей активации для SchoolPlanner
# Этот файл — для РАЗРАБОТЧИКА, а не для пользователя.
# Через него я генерирую ключи, которые потом отдаю пользователям.

# Как это работает:
#   1. Я запускаю файл в терминале: python keygen.py
#   2. Программа спрашивает: сколько ключей сгенерировать?
#   3. Я ввожу число (например, 10).
#   4. Программа выводит 10 ключей вида: SP-XXXX-XXXX-XXXX
#   5. Я копирую ключи и отдаю их пользователям.
#
# ВАЖНО: этот файл НИКОМУ нельзя отдавать! Только у меня на компьютере.



# Импортируем sys(встроенный модуль Python для работы
#  с операционной системой от имени программы)
#  нужен, чтобы завершать программу при ошибке
import sys

# Импортируем функцию _generate_key_from_number из файла license.py
# В ней спрятана формула, по которой генерируются ключи.
# Нижнее подчёркивание в начале имени означает, что функция «внутренняя» —
# но мы её всё равно используем, потому что она мне нужна здесь.
from license import _generate_key_from_number


def generate_keys(count, start_from=1):
    """
    Генерирует нужное количество ключей.

    Что принимает:
        count (int) — сколько ключей нужно сгенерировать
        start_from (int) — с какого номера начинать (по умолчанию с 1)

    Что возвращает:
        список из пар (номер, ключ)

    Зачем нужен start_from:
        Если уже выдано 10 ключей, в следующий раз надо начинать с 11,
        чтобы ключи не повторялись.
    """
    # Создаём пустой список, куда будем складывать ключи
    keys = []

    # Идём от start_from до start_from + count
    # Например, если start_from=1 и count=10, то цикл пройдёт по 1,2,3,...,10
    for n in range(start_from, start_from + count):

        # Для каждого номера вызываем функцию из license.py,
        # она возвращает готовый ключ (например, "SP-A3B7-C9D2-E5F1")
        key = _generate_key_from_number(n)

        # Добавляем в список пару: (номер, ключ)
        # Так я потом смогу понять, под каким номером какой ключ
        keys.append((n, key))

    # Возвращаем готовый список
    return keys


def main():
    """
    Главная функция — общается с пользователем в терминале.

    Здесь:
        - спрашивается, сколько ключей надо;
        - спрашивается, с какого номера начать;
        - вызывается generate_keys();
        - выводятся ключи на экран;
        - выдается предложение сохранить их в файл keys.txt.
    """

    # Красивый заголовок, чтобы было понятно, что это за программа
    print("=" * 60)
    print("  🔑 Генератор ключей SchoolPlanner")
    print("=" * 60)
    print()


    # Спрашиваем, сколько ключей сгенерировать

    try:
        # input() — ждем, пока пользователь введёт текст
        # .strip() — убираем лишние пробелы по краям
        count_str = input("Сколько ключей сгенерировать? [по умолчанию 10]: ").strip()

        # Если пользователь ничего не ввёл — ставим значение по умолчанию, пусть будет 5
        # Если ввёл — превращаем строку в число (int)
        count = int(count_str) if count_str else 5

    except ValueError:
        # Сюда попадаем, если пользователь ввёл не число
        print("❌ Ошибка: нужно ввести число.")

        sys.exit(1)
        # sys.exit(1) немедленно завершает программу, 1
        #  (1) означает: программа завершается с ошибкой, sys.exit(0) или просто sys.exit() — завершилась успешно
        # число 1 — это код выхода: 0 = успех, 1 (или другое) = ошибка.
        # так система понимает, что программа завершилась неудачно.


    # Проверка что число должно быть больше нуля
    if count <= 0:
        print("❌ Ошибка: количество должно быть больше 0.")
        sys.exit(1)

    # Если ключей больше 1000 — предупреждаем
    if count > 1000:
        print("⚠️ Внимание: больше 1000 ключей за раз — не рекомендуется.")


    # Спрашиваем, с какого номера начать

    try:
        start_str = input("Начать с номера? [по умолчанию 1]: ").strip()
        start_from = int(start_str) if start_str else 1

    except ValueError:
        # также сообщается, если пользователь ввёл не число
        print("❌ Ошибка: нужно ввести число.")
        sys.exit(1)


    # Генерируем ключи

    print() #добавил пустые строки в выводе
    print(f"Генерирую {count} ключей, начиная с #{start_from}...")
    print()

    # Вызываем функцию и получаем список пар
    keys = generate_keys(count, start_from)

    #
    # Выводим ключи на экран
    #
    print("=" * 60) # просто для выделения и оформления
    print(f"  Сгенерировано {len(keys)} ключей:")
    print("=" * 60)

    # Идём по списку и печатаем каждый ключ с номером
    # :<5 — выравнивание по левому краю шириной 5 символов (для красоты)
    for n, key in keys:
        print(f"  #{n:<5}  {key}")

    print("=" * 60) #опять для красоты
    print()

    #
    # Предлагаем сохранить в файл
    #
    save_to_file = input("Сохранить в файл keys.txt? [y/n]: ").strip().lower()

    # Проверяем, что пользователь ввёл «y», «yes», «да» или «д»
    if save_to_file in ("y", "yes", "да", "д"):
        filename = "keys.txt"

        try:
            # Открываем файл на запись ('w' — write)
            # encoding="utf-8" — чтобы русские буквы сохранялись правильно
            with open(filename, "w", encoding="utf-8") as f:

                # Пишем заголовок
                f.write("=" * 60 + "\n")
                f.write(f"  Ключи SchoolPlanner — {len(keys)} шт.\n")
                f.write("=" * 60 + "\n\n")

                # Пишем каждый ключ с новой строки
                for n, key in keys:
                    f.write(f"#{n:<5}  {key}\n")

            print(f"✅ Сохранено в {filename}")

        except IOError as e:
            # Сюда попадаем, если файл не удалось сохранить
            # (например, нет прав на запись)
            print(f"❌ Не удалось сохранить: {e}")

    else:
        print("Ключи не сохранены в файл.")

    # Финальное сообщение
    print()
    print("Готово! Отдай ключи пользователям.")
    print("Пользователь вводит ключ в программе → активация.")



if __name__ == "__main__":
    main()

# это «точка входа» — стандартный приём Python.
# __name__ — специальная переменная: если файл запущен напрямую,
# в ней лежит "__main__", а если импортирован — имя модуля ("keygen").
# Благодаря этой проверке main() запустится ТОЛЬКО при прямом запуске
# (python keygen.py), но НЕ при импорте (import keygen) из другого файла.
